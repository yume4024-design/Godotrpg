"""Adapt one licensed Kenney Nature Kit mesh; no whole-kit game import."""
import argparse
import hashlib
import json
from pathlib import Path
import sys
import bmesh
import bpy
from mathutils import Vector

p = argparse.ArgumentParser()
p.add_argument('--input', required=True, type=Path)
p.add_argument('--output', required=True, type=Path)
a = p.parse_args(sys.argv[sys.argv.index('--')+1:])
assert not a.output.exists(), 'New output directory required'
source_sha = hashlib.sha256(a.input.read_bytes()).hexdigest()
assert source_sha == 'e7a92369062d491e5a31a163d390e07db04ee573605bbfa84c00660d18896b4c'
bpy.ops.wm.read_factory_settings(use_empty=True)
bpy.ops.import_scene.gltf(filepath=str(a.input.resolve()))
meshes = [obj for obj in bpy.context.scene.objects if obj.type == 'MESH']
assert len(meshes) == 1
body = meshes[0]
bpy.ops.object.select_all(action='DESELECT')
body.select_set(True)
bpy.context.view_layer.objects.active = body
world = body.matrix_world.copy()
for vertex in body.data.vertices:
    vertex.co = world @ vertex.co
body.parent = None
body.matrix_world.identity()
for empty in list(bpy.context.scene.objects):
    if empty.type == 'EMPTY':
        bpy.data.objects.remove(empty, do_unlink=True)
low = Vector([min(v.co[i] for v in body.data.vertices) for i in range(3)])
high = Vector([max(v.co[i] for v in body.data.vertices) for i in range(3)])
factor = 3.0/(high.x-low.x)
for vertex in body.data.vertices:
    vertex.co = Vector(((vertex.co.x-(low.x+high.x)*.5)*factor,
                        (vertex.co.y-(low.y+high.y)*.5)*factor,
                        (vertex.co.z-low.z)*factor))
body.name = 'FallenLog'
palette = {'woodBark': ('wood', (.43,.29,.16)),
           'woodInner': ('wood_cut', (.73,.54,.32))}
for material in body.data.materials:
    name, rgb = palette[material.name]
    material.name = 'G04_'+name
    shader = next(node for node in material.node_tree.nodes if node.type == 'BSDF_PRINCIPLED')
    shader.inputs['Base Color'].default_value = (*[c/12.92 if c<=.04045 else ((c+.055)/1.055)**2.4 for c in rgb],1)
    shader.inputs['Roughness'].default_value = .9
# One broad chamfer makes the square-cut source less box-like. No subdivision,
# large texture, extra foliage, or duplicate source model is introduced.
bm = bmesh.new()
bm.from_mesh(body.data)
bmesh.ops.remove_doubles(bm, verts=list(bm.verts), dist=1e-6)
bmesh.ops.recalc_face_normals(bm, faces=list(bm.faces))
bm.to_mesh(body.data)
bm.free()
bevel = body.modifiers.new('SoftFacetCorners','BEVEL')
bevel.width = .065
bevel.segments = 1
bevel.limit_method = 'ANGLE'
bevel.angle_limit = .52
bevel.use_clamp_overlap = True
bpy.ops.object.modifier_apply(modifier=bevel.name)
bm = bmesh.new()
bm.from_mesh(body.data)
degenerate = [face for face in bm.faces if face.calc_area() <= 1e-10]
removed_degenerate_faces = len(degenerate)
bmesh.ops.delete(bm, geom=degenerate, context='FACES')
bm.to_mesh(body.data)
bm.free()
floor = min(vertex.co.z for vertex in body.data.vertices)
for vertex in body.data.vertices:
    vertex.co.z -= floor
for polygon in body.data.polygons:
    polygon.use_smooth = False
body.data.calc_loop_triangles()
triangles = len(body.data.loop_triangles)
assert 96 < triangles <= 1000, 'Explicit fallen-log budget'
points = [v.co for v in body.data.vertices]
bounds = [[min(v[i] for v in points),max(v[i] for v in points)] for i in range(3)]
assert abs(bounds[0][1]-bounds[0][0]-3.0)<.001
assert abs(bounds[2][0])<.001
a.output.mkdir(parents=True)
native,glb = a.output/'fallen_log.blend',a.output/'fallen_log.glb'
bpy.ops.file.pack_all()
bpy.ops.wm.save_as_mainfile(filepath=str(native.resolve()))
bpy.ops.export_scene.gltf(filepath=str(glb.resolve()),export_format='GLB',use_selection=True,export_animations=False)
report = {'source':str(a.input),'source_sha256':source_sha,
          'author':'Kenney','license':'CC0 1.0','archive_license_version':'Nature Kit (2.1)',
          'source_triangles':96,'adapted_triangles':triangles,'budget':1000,'bounds_blender_xyz':bounds,
          'removed_degenerate_bevel_faces':removed_degenerate_faces,
          'modifications':['Apply source transforms, 3m length, Y-up Godot via glTF, ground-center origin',
                           'Weld coincident source face seams within 1 micrometre; one-segment .065m chamfer; flat shading',
                           'Replace original peach bark with shared Greystone wood/cut-wood palette'],
          'textures':False,'materials':['G04_wood','G04_wood_cut'],
          'outputs':{p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in [native,glb]},
          'limitations':['Existing UV data is retained/generated by modifier; no production UV unwrap claimed',
                         'Standalone prop; no formal forest placement or gameplay/performance acceptance']}
(a.output/'adaptation.json').write_text(json.dumps(report,indent=2),encoding='utf8')
print('KENNEY_LOG_ADAPTED',triangles,flush=True)
